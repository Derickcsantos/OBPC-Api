execute function public.set_updated_at();

drop trigger if exists trg_planos_estudo_leituras_updated_at on public.planos_estudo_leituras;
create trigger trg_planos_estudo_leituras_updated_at
before update on public.planos_estudo_leituras
for each row
execute function public.set_updated_at();

