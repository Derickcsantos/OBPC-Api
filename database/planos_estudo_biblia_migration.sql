begin;

create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.planos_estudo (
  plano_estudo_id uuid primary key default gen_random_uuid(),
  titulo varchar(150) not null check (length(trim(titulo)) > 0),
  slug varchar(120) not null unique check (length(trim(slug)) > 0),
  descricao text,
  tipo varchar(50) not null default 'biblia' check (length(trim(tipo)) > 0),
  duracao_dias integer not null check (duracao_dias > 0),
  ativo boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.planos_estudo_dias (
  plano_estudo_dia_id uuid primary key default gen_random_uuid(),
  plano_estudo_id uuid not null references public.planos_estudo(plano_estudo_id) on delete cascade,
  dia integer not null check (dia > 0),
  titulo varchar(150),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (plano_estudo_id, dia)
);

create table if not exists public.planos_estudo_leituras (
  plano_estudo_leitura_id uuid primary key default gen_random_uuid(),
  plano_estudo_dia_id uuid not null references public.planos_estudo_dias(plano_estudo_dia_id) on delete cascade,
  ordem integer not null check (ordem > 0),
  book_id integer not null references public.books(id) on delete restrict,
  chapter integer not null check (chapter > 0),
  verse_start integer not null default 1 check (verse_start > 0),
  verse_end integer check (verse_end is null or verse_end >= verse_start),
  versao varchar(20) not null default 'ara' check (length(trim(versao)) > 0),
  versiculo_inicio_id bigint,
  versiculo_fim_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (plano_estudo_dia_id, ordem)
);

create index if not exists idx_planos_estudo_tipo_ativo
  on public.planos_estudo (tipo, ativo);
create index if not exists idx_planos_estudo_dias_plano_dia
  on public.planos_estudo_dias (plano_estudo_id, dia);
create index if not exists idx_planos_estudo_leituras_dia_ordem
  on public.planos_estudo_leituras (plano_estudo_dia_id, ordem);
create index if not exists idx_planos_estudo_leituras_book_chapter
  on public.planos_estudo_leituras (book_id, chapter);
create index if not exists idx_planos_estudo_leituras_versiculos
  on public.planos_estudo_leituras (versiculo_inicio_id, versiculo_fim_id);

drop trigger if exists trg_planos_estudo_updated_at on public.planos_estudo;
create trigger trg_planos_estudo_updated_at
before update on public.planos_estudo
for each row
execute function public.set_updated_at();

drop trigger if exists trg_planos_estudo_dias_updated_at on public.planos_estudo_dias;
create trigger trg_planos_estudo_dias_updated_at
before update on public.planos_estudo_dias
